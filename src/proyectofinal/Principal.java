    private void bloquearPestanas() {
    for (int i = 1; i < tabPrincipal.getTabCount(); i++) {
        tabPrincipal.setEnabledAt(i, false);
    }
    tabPrincipal.setSelectedIndex(0);
}

public void iniciarSesion(String rol, String nombre) {
    tabPrincipal.setEnabledAt(1, true);                  // Catálogo: todos
    if (rol.equals("Administrador") || rol.equals("Bibliotecario")) {
        tabPrincipal.setEnabledAt(2, true);              // Préstamos
    }
    if (rol.equals("Administrador")) {
        tabPrincipal.setEnabledAt(3, true);              // Biblioteca
    }
    tabPrincipal.setSelectedIndex(1);
    setTitle("Biblioteca TECSUP - " + nombre + " (" + rol + ")");
    javax.swing.JOptionPane.showMessageDialog(this, "Bienvenido/a, " + nombre + ".");
}

